// Cuts the Phosphor icon fonts and styles down to the icons the app uses, into src/styles/icons/.
//
// @phosphor-icons/web holds every icon (about 1,500) in two weights: 3,060 style rules and two fonts of
// about 140 KB each, where the app draws about 60 icons. This reads the icon names out of the sources
// and writes, for each weight, a stylesheet with just those rules and a woff2 font with just those glyphs.
// Run it (npm run icons:subset) after using an icon that is not in the list; src/icons.test.ts fails
// until you do. The package is a devDependency, so the output is committed.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import subsetFont from 'subset-font';

const PACKAGE = 'node_modules/@phosphor-icons/web/src';
const OUT = 'src/styles/icons';
const WEIGHTS = [
  { dir: 'regular', font: 'Phosphor', base: '.ph' },
  { dir: 'fill', font: 'Phosphor-Fill', base: '.ph-fill' },
];

/** Every `ph-<name>` written in the app's sources (tests excepted). Both weights get every name: either may use it. */
export function usedNames(root = 'src') {
  const names = new Set();
  const walk = (dir) => {
    for (const e of readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, e.name);
      if (e.isDirectory()) walk(file);
      else if (/\.(ts|tsx)$/.test(e.name) && !/\.test\.tsx?$/.test(e.name)) {
        for (const m of readFileSync(file, 'utf8').matchAll(/\bph-([a-z0-9]+(?:-[a-z0-9]+)*)/g)) names.add(m[1]);
      }
    }
  };
  walk(root);
  return names;
}

/** The style rules of one weight: its font-face, its base class and the codepoint of each icon. */
export function readWeight(dir, base) {
  const css = readFileSync(path.join(PACKAGE, dir, 'style.css'), 'utf8');
  const fontFace = /@font-face\s*\{[\s\S]*?\n\}/.exec(css)?.[0];
  const block = new RegExp(`^\\${base}\\s*\\{[\\s\\S]*?\\n\\}`, 'm').exec(css)?.[0];
  if (!fontFace || !block) throw new Error(`Unexpected stylesheet for ${dir}`);
  const icons = new Map();
  for (const m of css.matchAll(/^\.ph(?:-fill)?\.ph-([a-z0-9-]+):before\s*\{\s*content:\s*"\\([0-9a-f]+)";\s*\}/gm)) icons.set(m[1], m[2]);
  return { fontFace, block, icons };
}

async function main() {
  const used = usedNames();
  mkdirSync(OUT, { recursive: true });
  for (const { dir, font, base } of WEIGHTS) {
    const { fontFace, block, icons } = readWeight(dir, base);
    // `ph-fill` itself is a class name, not an icon.
    const names = [...used].filter((n) => icons.has(n)).sort();
    const text = names.map((n) => String.fromCodePoint(parseInt(icons.get(n), 16))).join('');
    const subset = await subsetFont(readFileSync(path.join(PACKAGE, dir, `${font}.woff2`)), text, { targetFormat: 'woff2' });
    writeFileSync(path.join(OUT, `${font}.woff2`), subset);
    // Chromium takes the woff2; the package's woff, ttf and svg copies are fallbacks for browsers this app never runs in.
    const face = fontFace.replace(/src:[\s\S]*?;/, `src: url("./${font}.woff2") format("woff2");`);
    const rules = names.map((n) => `${base}.ph-${n}:before {\n  content: "\\${icons.get(n)}";\n}`);
    writeFileSync(path.join(OUT, `${dir}.css`), [
      `/* Generated by scripts/icons-subset.mjs from @phosphor-icons/web (Copyright (c) 2020-2021 Phosphor Icons, MIT License): ${names.length} icons. Do not edit. */`,
      face, block, ...rules, '',
    ].join('\n'));
    console.log(`${dir}: ${names.length} icons, ${(subset.length / 1024).toFixed(1)} KB font`);
  }
}

if (import.meta.url === `file://${process.argv[1]}`) await main();
